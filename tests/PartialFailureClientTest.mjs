import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import '../public/assets/js/metric-finalizer.js';
const app = readFileSync(new URL('../public/assets/js/app.js', import.meta.url), 'utf8');
const source = app.slice(app.indexOf('    const submitArchitecture ='), app.indexOf('    const finalizationNotice'));
let calls = [];
let reports = [];
let failure = true;
const reporter = new globalThis.RFV2MetricFinalizer(async payload => { reports.push(payload); });
const context = vm.createContext({httpFailureReporter: reporter, request: async (route) => {
    calls.push(route);
    if (route.endsWith('-a') && failure) throw new Error('response lost');
    return {architecture: route.endsWith('-a') ? 'A' : 'B', status:'unknown', metrics:{}};
}});
vm.runInContext(source+'\nglobalThis.submit = submitArchitecture;', context);
const body = JSON.stringify({session_token:'0123456789abcdef0123456789abcdef',frame_sequence:7});
await assert.rejects(context.submit('A', body), error => error.httpFailure === true);
assert.equal((await context.submit('B', body)).architecture, 'B');
await reporter.retryPending();
assert.equal(reports.length,1);
assert.deepEqual(calls,['session-frame-a','session-frame-b'], 'Recovery must not resubmit recognition');
assert.equal(reports[0].frame_sequence,7);
failure = false;
assert.equal((await context.submit('A',body)).status,'unknown');
const importScript = readFileSync(new URL('../public/assets/js/import.js', import.meta.url),'utf8');
const prepare = importScript.slice(importScript.indexOf('    const prepareImage ='),importScript.indexOf('    const processPending ='));
let closed = false;
const canvas = {getContext:()=>({drawImage(){}}),toDataURL:()=> 'jpeg'};
const importContext = vm.createContext({importCapabilities:()=>({maximum_image_bytes:1000,minimum_dimension:10,maximum_pixels:10000}), createImageBitmap:async()=>({width:20,height:20,close(){closed=true;}}),document:{createElement:()=>canvas},window:{rfv2FaceApi:{extractFromCanvas:async()=>{throw Object.assign(new Error('no face'),{rfv2FailureCode:'no_face'});}}}});
vm.runInContext(prepare+'\nglobalThis.prepare = prepareImage;',importContext);
const result = await importContext.prepare({size:100});
assert.equal(result.embedding,null);
assert.equal(result.failure,'no_face');
assert.equal(result.image,'jpeg','A failure must preserve B image');
assert.ok(closed);
let faceApiCalls = 0;
const retryContext = vm.createContext({importCapabilities:()=>({maximum_image_bytes:1000,minimum_dimension:10,maximum_pixels:10000}), createImageBitmap:async()=>({width:20,height:20,close(){}}),document:{createElement:()=>canvas},window:{rfv2FaceApi:{extractFromCanvas:async()=>{faceApiCalls++; return {embedding:[1]};}}}});
vm.runInContext(prepare+'\nglobalThis.prepare = prepareImage;', retryContext);
await retryContext.prepare({size:100}, false);
assert.equal(faceApiCalls, 0, 'Retomada de B nao pode repetir a extracao A ja persistida.');
const storage = new Map();
const persisted = {getItem: () => storage.get('pending') || null, setItem: value => storage.set('pending', JSON.stringify(value)), removeItem: () => storage.delete('pending')};
const interrupted = new globalThis.RFV2MetricFinalizer(async () => { throw new Error('offline'); }, 3, persisted);
await interrupted.submit({session_token:'0123456789abcdef0123456789abcdef', frame_sequence:8, architecture:'A'});
assert.ok(storage.has('pending'), 'Falha HTTP pendente precisa sobreviver ao ciclo da pagina.');
let restoredCalls = 0;
const restored = new globalThis.RFV2MetricFinalizer(async () => { restoredCalls++; }, 3, persisted);
await restored.retryPending();
assert.equal(restoredCalls, 1, 'Reload deve recuperar a pendencia HTTP sem reenviar o reconhecimento.');
assert.equal(storage.has('pending'), false, 'Pendencia HTTP so pode ser limpa apos confirmacao.');
console.log('OK - isolamento de extracao e recuperacao HTTP persistida sem reenviar reconhecimento');
